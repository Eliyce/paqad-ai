import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { describe, expect, it } from 'vitest';

import {
  CATALOG_VERSION,
  generateConfigExample,
  generateConfigsReadme,
} from '@/core/framework-config.js';
import { MANAGED_BLOCK_VERSION } from '@/onboarding/gitignore-writer.js';

const REPO = resolve(__dirname, '../../..');
const sha = (text: string) =>
  createHash('sha256').update(text.replace(/\r\n/gu, '\n')).digest('hex');
const launcher = readFileSync(join(REPO, 'runtime/templates/team-bootstrap/hook.mjs'), 'utf8');
const writer = readFileSync(join(REPO, 'src/onboarding/gitignore-writer.ts'), 'utf8');

function managedEntries(source: string): string {
  const start = source.indexOf('const MANAGED_GITIGNORE_ENTRIES = [');
  return source.slice(start, source.indexOf('];', start));
}

const PINS = {
  catalog: { version: 1, hash: 'e3e0a8c3ae299ac17dd0d9750b682a2874d11cdf60ad61406f7e31b901c4cb8f' },
  readme: { version: 1, hash: '1263b387250be4f5610ea8a06aa9ad2069aeacb87e0fb82d1527c0afcbafee08' },
  launcher: {
    version: 1,
    hash: 'c85bc81248d747c461b81f18784fa5e06fff08a8b1ba1721dcb61f189f745ab9',
  },
  block: { version: 1, hash: 'cd0e5008876189706109cc03f16139970b5f6247d619c0efd1dd47d839aa3414' },
};

describe('a file changes only with its integer', () => {
  it('AC-25: the catalog holds its integer', () => {
    expect(
      { version: CATALOG_VERSION, hash: sha(generateConfigExample()) },
      'The catalog changed. Raise CATALOG_VERSION and update this pin.',
    ).toEqual(PINS.catalog);
  });

  it('AC-25: the configs README holds the catalog integer', () => {
    expect(
      { version: CATALOG_VERSION, hash: sha(generateConfigsReadme()) },
      'The configs README changed. Raise CATALOG_VERSION and update this pin.',
    ).toEqual(PINS.readme);
  });

  it('AC-25: the launcher template holds its revision', () => {
    const revision = Number(/LAUNCHER_REVISION = (\d+);/u.exec(launcher)?.[1]);
    expect(
      { version: revision, hash: sha(launcher) },
      'The launcher changed. Raise LAUNCHER_REVISION and update this pin.',
    ).toEqual(PINS.launcher);
  });

  it('AC-25: the managed ignore block holds its integer', () => {
    expect(
      { version: MANAGED_BLOCK_VERSION, hash: sha(managedEntries(writer)) },
      'The managed ignore entries changed. Raise MANAGED_BLOCK_VERSION and update this pin.',
    ).toEqual(PINS.block);
  });
});

describe('no version is left in the stamped files', () => {
  it('AC-20: a version-only release changes neither the catalog nor the launcher', () => {
    expect(generateConfigExample()).not.toMatch(/generated by paqad-ai/u);
    expect(launcher).not.toContain('__PAQAD_VERSION__');
    expect(launcher).toMatch(/'revision=' \+ LAUNCHER_REVISION/u);
  });
});
