import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  utimesSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import YAML from 'yaml';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { PATHS } from '@/core/constants/paths.js';
import { defaultFeatureDevelopmentPolicy } from '@/pipeline/feature-development-policy.js';
import {
  FEATURE_DEVELOPMENT_VIEW_HEADER,
  featureDevelopmentViewPath,
  rebuildFeatureDevelopmentView,
  refreshFeatureDevelopmentView,
  renderFeatureDevelopmentView,
  viewEditedByHand,
} from '@/pipeline/feature-development-view.js';
import { SchemaValidator } from '@/validators/validator.js';
import {
  maybeSpawnViewRefresh,
  viewRefreshDue,
} from '../../../runtime/hooks/lib/feature-view-refresh.mjs';

let root: string;

function write(rel: string, text: string): void {
  const path = join(root, rel);
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, text, 'utf8');
}

function view(): string {
  return readFileSync(featureDevelopmentViewPath(root), 'utf8');
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'feature-view-'));
  write(PATHS.PROJECT_PROFILE, 'active_capabilities:\n  - coding\n');
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('the generated feature-development view', () => {
  it('starts with the verbatim header and validates as a workflow policy', () => {
    expect(FEATURE_DEVELOPMENT_VIEW_HEADER).toBe(
      [
        '# Generated by paqad. Do not edit: changes here are overwritten.',
        "# This shows how the feature-development workflow runs in this project: paqad's own",
        "# stage instructions plus this team's additions from .paqad/configs/feature-development/.",
        '# To change it, edit those files.',
        '',
      ].join('\n'),
    );
    const text = renderFeatureDevelopmentView(defaultFeatureDevelopmentPolicy());
    const result = new SchemaValidator().validate('feature-development-policy', YAML.parse(text));
    expect(result.valid).toBe(true);
  });

  it('is written with its hash and left alone when nothing changed', () => {
    expect(refreshFeatureDevelopmentView(root).status).toBe('written');
    expect(view().startsWith(FEATURE_DEVELOPMENT_VIEW_HEADER)).toBe(true);
    expect(existsSync(join(root, PATHS.FEATURE_DEVELOPMENT_VIEW_HASH))).toBe(true);
    expect(refreshFeatureDevelopmentView(root).status).toBe('unchanged');
  });

  it('AC-58: is rebuilt when a source file changes', () => {
    refreshFeatureDevelopmentView(root);
    write(
      '.paqad/configs/feature-development/workflow.yaml',
      'stages:\n  review:\n    instructions: [Team rule.]\n',
    );
    expect(refreshFeatureDevelopmentView(root).status).toBe('written');
    const parsed = YAML.parse(view()) as { stages: { review: { instructions: string[] } } };
    expect(parsed.stages.review.instructions.at(-1)).toBe('Team rule.');
  });

  it('AC-59: moves a hand edit into the YAML files, prints it, then rebuilds', () => {
    refreshFeatureDevelopmentView(root);
    const parsed = YAML.parse(view()) as {
      stages: Record<
        string,
        { instructions: string[]; checks: { shell_commands: string[] } | null }
      >;
    };
    parsed.stages.development!.instructions.push('Hand-written rule.');
    parsed.stages.checks!.checks!.shell_commands.push('pnpm lint:js');
    writeFileSync(
      featureDevelopmentViewPath(root),
      `${FEATURE_DEVELOPMENT_VIEW_HEADER}${YAML.stringify(parsed)}`,
    );
    expect(viewEditedByHand(root)).toBe(true);

    const lines = rebuildFeatureDevelopmentView(root);

    expect(lines).toEqual([
      'docs/instructions/workflows/feature-development.yaml was edited by hand; paqad moved the edit and rebuilt it.',
      'Moved your edit to docs/instructions/workflows/feature-development.yaml into .paqad/configs/feature-development/workflow.yaml: stages.development.instructions.',
      'Moved your edit to docs/instructions/workflows/feature-development.yaml into .paqad/configs/feature-development/checks.yaml: commands.extra.',
    ]);
    expect(
      YAML.parse(
        readFileSync(join(root, '.paqad/configs/feature-development/workflow.yaml'), 'utf8'),
      ),
    ).toMatchObject({ stages: { development: { instructions: ['Hand-written rule.'] } } });
    expect(
      YAML.parse(readFileSync(join(root, '.paqad/configs/feature-development/checks.yaml'), 'utf8'))
        .commands.extra,
    ).toEqual({ 'command-1': 'pnpm lint:js' });
    expect(viewEditedByHand(root)).toBe(false);
    expect(view()).toContain('Hand-written rule.');
  });

  it('leaves an old team-edited workflow file for the migration', () => {
    write('docs/instructions/workflows/feature-development.yaml', 'schema_version: "1"\n');
    expect(refreshFeatureDevelopmentView(root).status).toBe('legacy');
    expect(view()).toBe('schema_version: "1"\n');
  });

  it('writes nothing for a content project', () => {
    write(PATHS.PROJECT_PROFILE, 'active_capabilities:\n  - content\n');
    expect(refreshFeatureDevelopmentView(root).status).toBe('skipped');
    expect(existsSync(featureDevelopmentViewPath(root))).toBe(false);
  });
});

describe('the SessionStart refresh', () => {
  it('spawns the CLI rebuild off the hook path when a source is newer than the view', () => {
    expect(viewRefreshDue(root)).toBe(true);
    refreshFeatureDevelopmentView(root);
    expect(viewRefreshDue(root)).toBe(false);
    write('.paqad/configs/feature-development/checks.yaml', 'on_failure: warn\n');
    const later = new Date(Date.now() + 5000);
    utimesSync(join(root, '.paqad/configs/feature-development/checks.yaml'), later, later);
    expect(viewRefreshDue(root)).toBe(true);
    const calls: unknown[][] = [];
    const spawned = maybeSpawnViewRefresh({
      projectRoot: root,
      cliPath: '/cli/index.js',
      env: {},
      spawn: (...args: unknown[]) => {
        calls.push(args);
        return { unref: () => {}, on: () => {} };
      },
    });
    expect(spawned).toBe(true);
    expect(calls[0]![1]).toEqual(['/cli/index.js', 'config', 'view', '--project-root', root]);
    expect(calls[0]![2]).toMatchObject({ detached: true, stdio: 'ignore' });
  });

  it('never throws when the spawn fails', () => {
    expect(
      maybeSpawnViewRefresh({
        projectRoot: root,
        cliPath: '/cli/index.js',
        spawn: () => {
          throw new Error('boom');
        },
      }),
    ).toBe(false);
  });
});
