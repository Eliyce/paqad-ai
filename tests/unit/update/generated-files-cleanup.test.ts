import { execFileSync } from 'node:child_process';
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { removeGeneratedFiles } from '@/update/generated-files-cleanup.js';
import { WorkflowTemplateLoader } from '@/workflows/template-loader.js';

const COPY = 'docs/instructions/workflows/feature-development.yaml';
const HASH = '.paqad/state/feature-development-view.sha256';
const MARKER = '# paqad-ai: generated on each machine';
const GENERATED =
  '# Generated by paqad. Do not edit: changes here are overwritten.\nschema_version: "1"\n';
const PAQAD_YAML_BODY = '# Turns paqad on.\npaqad_version: "1.117.0"\nenabled: true\n';
const COPY_LINE =
  'Removed the generated workflow copy docs/instructions/workflows/feature-development.yaml; paqad reads .paqad/configs/ directly.';

let root: string;

function write(rel: string, text: string): void {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), text, 'utf8');
}

function read(rel: string): string {
  return readFileSync(join(root, rel), 'utf8');
}

function oldProject(): void {
  execFileSync('git', ['init', '-q'], { cwd: root });
  write(COPY, GENERATED);
  write(HASH, 'abc\n');
  write('.git/info/exclude', `# git ls-files --others\n${MARKER}\n/${COPY}\n`);
  write('.paqad/configs/schemas/paqad.schema.json', '{}\n');
  write(
    '.paqad/configs/paqad.yaml',
    `# yaml-language-server: $schema=./schemas/paqad.schema.json\n${PAQAD_YAML_BODY}`,
  );
  write(
    '.paqad/configs/feature-development/checks.yaml',
    '# yaml-language-server: $schema=../schemas/feature-development/checks.schema.json\non_failure: warn\n',
  );
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'paqad-generated-cleanup-'));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe('removeGeneratedFiles', () => {
  it('removes every leftover with one line each, then prints nothing on a second run', () => {
    oldProject();
    expect(removeGeneratedFiles(root)).toEqual([
      COPY_LINE,
      'Removed .paqad/state/feature-development-view.sha256, which paqad used to check the workflow copy.',
      'Removed the line for docs/instructions/workflows/feature-development.yaml from .git/info/exclude.',
      'Removed the empty docs/instructions/workflows/ folder.',
      'Removed the empty docs/instructions/ folder.',
      'Removed .paqad/configs/schemas/; paqad no longer writes editor schemas.',
      'Removed the schema line at the top of .paqad/configs/paqad.yaml.',
      'Removed the schema line at the top of .paqad/configs/feature-development/checks.yaml.',
    ]);
    expect(existsSync(join(root, 'docs'))).toBe(true);
    expect(existsSync(join(root, 'docs/instructions'))).toBe(false);
    expect(existsSync(join(root, HASH))).toBe(false);
    expect(existsSync(join(root, '.paqad/configs/schemas'))).toBe(false);
    expect(read('.git/info/exclude')).toBe('# git ls-files --others\n');
    expect(read('.paqad/configs/paqad.yaml')).toBe(PAQAD_YAML_BODY);
    expect(read('.paqad/configs/feature-development/checks.yaml')).toBe('on_failure: warn\n');
    expect(removeGeneratedFiles(root)).toEqual([]);
  });

  it("keeps a team's own workflow and the folder, and the engine still lists it", async () => {
    oldProject();
    write('docs/instructions/workflows/rca.yaml', 'name: rca\nsteps: []\n');
    const lines = removeGeneratedFiles(root);
    expect(lines).toContain(COPY_LINE);
    expect(lines.some((line) => line.includes('empty'))).toBe(false);
    expect(read('docs/instructions/workflows/rca.yaml')).toBe('name: rca\nsteps: []\n');
    expect(await new WorkflowTemplateLoader(root).list()).toContain('rca');
  });

  it('leaves a hand-written workflow file for the migration', () => {
    write(COPY, 'schema_version: "1"\nstages: {}\n');
    expect(removeGeneratedFiles(root)).toEqual([]);
    expect(read(COPY)).toBe('schema_version: "1"\nstages: {}\n');
  });

  it('keeps docs/instructions/ when it still holds something', () => {
    write(COPY, GENERATED);
    write('docs/instructions/rules/a.md', '# a\n');
    expect(removeGeneratedFiles(root)).toEqual([
      COPY_LINE,
      'Removed the empty docs/instructions/workflows/ folder.',
    ]);
    expect(existsSync(join(root, 'docs/instructions/rules/a.md'))).toBe(true);
  });

  it('removes only the workflow-copy line and its marker from the exclude file', () => {
    execFileSync('git', ['init', '-q'], { cwd: root });
    write('.git/info/exclude', `${MARKER}\n/.paqad/other.json\n${MARKER}\n/${COPY}\n/tail-entry\n`);
    expect(removeGeneratedFiles(root)).toEqual([
      'Removed the line for docs/instructions/workflows/feature-development.yaml from .git/info/exclude.',
    ]);
    expect(read('.git/info/exclude')).toBe(`${MARKER}\n/.paqad/other.json\n/tail-entry\n`);
  });

  it('removes a schema line after a byte order mark, and the mark with it', () => {
    write(
      '.paqad/configs/paqad.yaml',
      `\uFEFF# yaml-language-server: $schema=./schemas/paqad.schema.json\n${PAQAD_YAML_BODY}`,
    );
    expect(removeGeneratedFiles(root)).toEqual([
      'Removed the schema line at the top of .paqad/configs/paqad.yaml.',
    ]);
    expect(read('.paqad/configs/paqad.yaml')).toBe(PAQAD_YAML_BODY);
  });

  it('removes a schema line ending in CRLF and keeps the CRLF lines after it', () => {
    const body = '# Turns paqad on.\r\npaqad_version: "1.117.0"\r\nenabled: true\r\n';
    write(
      '.paqad/configs/paqad.yaml',
      `# yaml-language-server: $schema=./schemas/paqad.schema.json\r\n${body}`,
    );
    expect(removeGeneratedFiles(root)).toEqual([
      'Removed the schema line at the top of .paqad/configs/paqad.yaml.',
    ]);
    expect(read('.paqad/configs/paqad.yaml')).toBe(body);
  });

  it('changes nothing outside a git repository and leaves a file without the schema line alone', () => {
    write('.paqad/configs/paqad.yaml', PAQAD_YAML_BODY);
    expect(removeGeneratedFiles(root)).toEqual([]);
    expect(read('.paqad/configs/paqad.yaml')).toBe(PAQAD_YAML_BODY);
  });

  it('names an item it could not remove, carries on, and removes it on the next run', () => {
    oldProject();
    const configs = join(root, '.paqad/configs');
    chmodSync(configs, 0o555);
    let lines: string[];
    try {
      lines = removeGeneratedFiles(root);
    } finally {
      chmodSync(configs, 0o755);
    }
    expect(lines).toContain(COPY_LINE);
    expect(
      lines.some((line) =>
        line.startsWith("Couldn't remove .paqad/configs/schemas/, so it stayed: "),
      ),
    ).toBe(true);
    expect(lines.at(-1)).toBe(
      'Removed the schema line at the top of .paqad/configs/feature-development/checks.yaml.',
    );
    expect(existsSync(join(configs, 'schemas'))).toBe(true);
    expect(removeGeneratedFiles(root)).toEqual([
      'Removed .paqad/configs/schemas/; paqad no longer writes editor schemas.',
    ]);
  });
});
