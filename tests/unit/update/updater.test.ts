function writeOldLeftovers(projectRoot: string): void {
  const put = (rel: string, text: string) => {
    mkdirSync(join(projectRoot, rel, '..'), { recursive: true });
    writeFileSync(join(projectRoot, rel), text, 'utf8');
  };
  put(
    'docs/instructions/workflows/feature-development.yaml',
    '# Generated by paqad. Do not edit: changes here are overwritten.\nstages: {}\n',
  );
  put('.paqad/state/feature-development-view.sha256', 'abc\n');
  put('.paqad/configs/schemas/paqad.schema.json', '{}\n');
  const exclude = join(projectRoot, '.git/info/exclude');
  const before = existsSync(exclude) ? readFileSync(exclude, 'utf8') : '';
  put(
    '.git/info/exclude',
    `${before}# paqad-ai: generated on each machine\n/docs/instructions/workflows/feature-development.yaml\n`,
  );
}

function removalLines(lines: string[]): string[] {
  return lines.filter((line) => line.startsWith('Removed ') || line.startsWith("Couldn't remove"));
}

