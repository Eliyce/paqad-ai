import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import YAML from 'yaml';

import { PATHS } from '@/core/constants/paths.js';
import { FRAMEWORK_CONFIG_SPECS } from '@/core/framework-config.js';
import { readTextIfExistsSync } from '@/core/fs/read-if-exists.js';
import { getProfileDomain, readProjectProfile } from '@/core/project-profile.js';
import { readTeamYamlFile, setTeamConfigValue, writeTeamYamlValue } from '@/core/team-config.js';
import { WORKFLOW_POLICY_STAGES } from '@/core/team-config-schema.js';
import type { FeatureDevelopmentPolicy } from '@/core/types/feature-development-policy.js';
import { excludeLocally } from '@/onboarding/gitignore-writer.js';

import { loadFeatureDevelopmentPolicy } from './feature-development-policy.js';

export const FEATURE_DEVELOPMENT_VIEW_FILE = 'feature-development.yaml';
export const FEATURE_DEVELOPMENT_VIEW_RELATIVE = `${PATHS.WORKFLOWS_DIR}/${FEATURE_DEVELOPMENT_VIEW_FILE}`;

export const FEATURE_DEVELOPMENT_VIEW_HEADER = [
  '# Generated by paqad. Do not edit: changes here are overwritten.',
  "# This shows how the feature-development workflow runs in this project: paqad's own",
  "# stage instructions plus this team's additions from .paqad/configs/feature-development/.",
  '# To change it, edit those files.',
  '',
].join('\n');

const WORKFLOW_FILE = 'feature-development/workflow.yaml' as const;
const CHECKS_FILE = 'feature-development/checks.yaml' as const;

export function isFeatureDevelopmentViewFile(fileName: string): boolean {
  return fileName === FEATURE_DEVELOPMENT_VIEW_FILE;
}

export function featureDevelopmentViewPath(projectRoot: string): string {
  return join(projectRoot, FEATURE_DEVELOPMENT_VIEW_RELATIVE);
}

export function isGeneratedView(text: string): boolean {
  return text.startsWith(FEATURE_DEVELOPMENT_VIEW_HEADER.split('\n')[0]!);
}

export function renderFeatureDevelopmentView(policy: FeatureDevelopmentPolicy): string {
  const stages = Object.fromEntries(
    Object.entries(policy.stages).map(([name, stage]) => {
      const { checks, ...rest } = stage;
      return [name, checks === null ? rest : stage];
    }),
  );
  return `${FEATURE_DEVELOPMENT_VIEW_HEADER}${YAML.stringify({ ...policy, stages }, { lineWidth: 0 })}`;
}

export function viewHash(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

function hashPath(projectRoot: string): string {
  return join(projectRoot, PATHS.FEATURE_DEVELOPMENT_VIEW_HASH);
}

export function readStoredViewHash(projectRoot: string): string | null {
  try {
    return readFileSync(hashPath(projectRoot), 'utf8').trim() || null;
  } catch {
    return null;
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function strings(value: unknown): string[] {
  return Array.isArray(value)
    ? value.filter((entry): entry is string => typeof entry === 'string' && entry.trim() !== '')
    : [];
}

function teamList(projectRoot: string, path: readonly string[]): string[] {
  const { document } = readTeamYamlFile(projectRoot, WORKFLOW_FILE);
  return strings(pathValue(document?.toJS(), path));
}

function pathValue(data: unknown, path: readonly string[]): unknown {
  let node = data;
  for (const segment of path) {
    if (!isRecord(node)) return undefined;
    node = node[segment];
  }
  return node;
}

function movedLine(file: string, path: string): string {
  return `Moved your edit to ${FEATURE_DEVELOPMENT_VIEW_RELATIVE} into .paqad/configs/${file}: ${path}.`;
}

export function carryWorkflowFields(
  projectRoot: string,
  edited: unknown,
  current: FeatureDevelopmentPolicy,
): string[] {
  const moved: string[] = [];
  const stages = isRecord(edited) && isRecord(edited.stages) ? edited.stages : {};
  for (const stage of WORKFLOW_POLICY_STAGES) {
    const raw = isRecord(stages[stage]) ? stages[stage] : {};
    for (const field of ['read', 'instructions'] as const) {
      const extra = strings(raw[field]).filter(
        (entry) => !current.stages[stage][field].includes(entry),
      );
      if (extra.length === 0) continue;
      const path = ['stages', stage, field];
      const existing = teamList(projectRoot, path);
      writeTeamYamlValue(projectRoot, WORKFLOW_FILE, path, [...existing, ...extra]);
      moved.push(movedLine(WORKFLOW_FILE, path.join('.')));
    }
  }
  const planning = isRecord(stages.planning) ? stages.planning : {};
  const attribution = isRecord(planning.escalation)
    ? planning.escalation.attribution_pending
    : undefined;
  if (
    (attribution === 'defer' || attribution === 'stop') &&
    attribution !== current.stages.planning.escalation.attribution_pending
  ) {
    writeTeamYamlValue(
      projectRoot,
      WORKFLOW_FILE,
      ['stages', 'planning', 'module_attribution'],
      attribution,
    );
    moved.push(movedLine(WORKFLOW_FILE, 'stages.planning.module_attribution'));
  }
  const checksStage = isRecord(stages.checks) ? stages.checks : {};
  const checks = isRecord(checksStage.checks) ? checksStage.checks : null;
  const base = current.stages.checks.checks;
  if (checks !== null && base !== null) {
    const names = checks.use_project_profile_commands === false ? [] : strings(checks.commands);
    const baseNames = base.use_project_profile_commands ? base.commands : [];
    if (
      (checks.use_project_profile_commands !== undefined || checks.commands !== undefined) &&
      names.join(',') !== baseNames.join(',')
    ) {
      writeTeamYamlValue(projectRoot, CHECKS_FILE, ['commands', 'from_project_profile'], names);
      moved.push(movedLine(CHECKS_FILE, 'commands.from_project_profile'));
    }
    const shell = strings(checks.shell_commands).filter(
      (command) => !base.shell_commands.includes(command),
    );
    if (shell.length > 0) {
      const { document } = readTeamYamlFile(projectRoot, CHECKS_FILE);
      const extra = pathValue(document?.toJS(), ['commands', 'extra']);
      let index = isRecord(extra) ? Object.keys(extra).length : 0;
      for (const command of shell) {
        index += 1;
        writeTeamYamlValue(
          projectRoot,
          CHECKS_FILE,
          ['commands', 'extra', `command-${index}`],
          command,
        );
      }
      moved.push(movedLine(CHECKS_FILE, 'commands.extra'));
    }
    if (
      typeof checks.block_on_failure === 'boolean' &&
      checks.block_on_failure !== base.block_on_failure
    ) {
      writeTeamYamlValue(
        projectRoot,
        CHECKS_FILE,
        ['on_failure'],
        checks.block_on_failure ? 'block' : 'warn',
      );
      moved.push(movedLine(CHECKS_FILE, 'on_failure'));
    }
  }
  const compliance = isRecord(checksStage.rule_compliance)
    ? checksStage.rule_compliance.mode
    : undefined;
  if (
    typeof compliance === 'string' &&
    compliance !== current.stages.checks.rule_compliance?.mode &&
    ['off', 'warn', 'strict'].includes(compliance)
  ) {
    const spec = FRAMEWORK_CONFIG_SPECS.find((row) => row.key === 'rule_compliance')!;
    setTeamConfigValue(projectRoot, 'rule_compliance', compliance);
    moved.push(movedLine(spec.file, spec.path.join('.')));
  }
  return moved;
}

export interface ViewRefreshResult {
  status: 'unchanged' | 'written' | 'legacy' | 'skipped';
  handEdited: boolean;
  moved: string[];
  warnings: string[];
}

function isCodingProject(projectRoot: string): boolean {
  if (!existsSync(join(projectRoot, PATHS.PROJECT_PROFILE))) return false;
  try {
    const profile = readProjectProfile(projectRoot, { persistMigration: false });
    return profile !== null && getProfileDomain(profile) === 'coding';
  } catch {
    return false;
  }
}

export function refreshFeatureDevelopmentView(projectRoot: string): ViewRefreshResult {
  const result: ViewRefreshResult = {
    status: 'unchanged',
    handEdited: false,
    moved: [],
    warnings: [],
  };
  if (!isCodingProject(projectRoot)) return { ...result, status: 'skipped' };
  const path = featureDevelopmentViewPath(projectRoot);
  const existing = readTextIfExistsSync(path);
  if (existing !== null && !isGeneratedView(existing)) return { ...result, status: 'legacy' };
  const stored = readStoredViewHash(projectRoot);
  if (existing !== null && stored !== null && viewHash(existing) !== stored) {
    result.handEdited = true;
    try {
      const edited: unknown = YAML.parse(existing);
      result.moved = carryWorkflowFields(
        projectRoot,
        edited,
        loadFeatureDevelopmentPolicy(projectRoot).policy,
      );
    } catch (error) {
      result.warnings.push(
        `${FEATURE_DEVELOPMENT_VIEW_RELATIVE} was edited by hand and couldn't be read, so the edit wasn't moved: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
  }
  const loaded = loadFeatureDevelopmentPolicy(projectRoot);
  result.warnings.push(...loaded.warnings);
  const text = renderFeatureDevelopmentView(loaded.policy);
  const hash = viewHash(text);
  excludeLocally(projectRoot, FEATURE_DEVELOPMENT_VIEW_RELATIVE);
  if (existing === text && stored === hash) return result;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text, 'utf8');
  mkdirSync(dirname(hashPath(projectRoot)), { recursive: true });
  writeFileSync(hashPath(projectRoot), `${hash}\n`, 'utf8');
  return { ...result, status: 'written' };
}

export function viewEditedByHand(projectRoot: string): boolean {
  const path = featureDevelopmentViewPath(projectRoot);
  const stored = readStoredViewHash(projectRoot);
  if (stored === null) return false;
  const text = readTextIfExistsSync(path);
  if (text === null) return false;
  return isGeneratedView(text) && viewHash(text) !== stored;
}

export function rebuildFeatureDevelopmentView(projectRoot: string): string[] {
  try {
    const result = refreshFeatureDevelopmentView(projectRoot);
    return result.handEdited
      ? [
          `${FEATURE_DEVELOPMENT_VIEW_RELATIVE} was edited by hand; paqad moved the edit and rebuilt it.`,
          ...result.moved,
        ]
      : result.moved;
  } catch (error) {
    return [
      `${FEATURE_DEVELOPMENT_VIEW_RELATIVE} couldn't be rebuilt: ${error instanceof Error ? error.message : String(error)}`,
    ];
  }
}
